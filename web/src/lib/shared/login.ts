// Тексты страницы входа, которые проверяются тестами.

/** Текст ошибки SSO по коду из callback: у каждой причины — своё «что делать». */
export function ssoErrorText(code: string, origin: string | null): string {
  if (code === "no_role") return "Вход через корпоративную учётную запись прошёл, но ваша группа не даёт доступа к ARGUS. Обратитесь к администратору, чтобы вас добавили в нужную группу.";
  if (code === "denied") return "Корпоративный вход не подтвердил учётную запись. Попробуйте ещё раз; если ошибка повторяется — обратитесь к администратору.";
  return `Сеанс входа устарел или начат с другого адреса. Начните вход заново${origin ? ` с ${origin}` : ""} и завершите его за 15 минут.`;
}
