-- Отметки вердиктов агента разбора: «вердикт по задаче N принят и
-- опубликован». Агент пишет её до публикации, сервер не выдаёт сессию разбора
-- по задаче с отметкой published. Повторный разбор — только после того, как
-- человек в консоли запишет reopened. Отметка живёт вне трекера: статус задачи
-- и её токен отметку не снимают.
--
-- Журнал без схлопывания: текущее состояние — последняя строка по updated_at,
-- а «чья сессия отметила первой после последнего reopened» — по истории
-- (условная отметка). ReplacingMergeTree по
-- task_id при слиянии оставил бы только последнюю строку, и победителя гонки
-- двух сессий нельзя было бы определить. TTL нет: отметка не должна истечь
-- раньше строки доставки, строк — единицы на задачу.
CREATE TABLE IF NOT EXISTS argus.triage_verdicts
(
    task_id     String,
    incident_id String,
    state       LowCardinality(String),
    session_id  String,
    actor       String,
    updated_at  DateTime64(3, 'UTC') DEFAULT now64(3)
)
ENGINE = MergeTree
ORDER BY (task_id, updated_at);
