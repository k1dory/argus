-- Свободный поиск по тексту: n-граммный индекс idx_text отсекает гранулы, в
-- которых искомой подстроки заведомо нет. Без него каждый запрос со словом
-- читал всё окно целиком (raw и все поля), а поиск запускал три таких запроса
-- одновременно: страницу, гистограмму и фасеты.
--
-- Выражение индекса совпадает с web/src/lib/search.ts (INDEXES.*.text.index)
-- символ в символ: иначе ClickHouse его не применит. Строковых констант в нём
-- нет намеренно: новый анализатор 24.8 не сопоставляет индекс на
-- concat(x, ' ', y). Поля склеены без разделителя — индекс только отсекает
-- гранулы, точная проверка подстроки остаётся по полям.
--
-- ngrambf_v1(4, 65536, 3, 0): n-граммы по 4 байта, 64 КиБ фильтра на гранулу
-- (8192 строки), 3 хеша. Около 6,5 байт индекса на строку: ~65 МиБ на 10 млн
-- событий. Слова короче 4 байт индекс не ускоряет.
--
-- Новые куски получают индекс сами. Старые читаются как раньше, пока индекс не
-- построен для них явно (тяжёлая мутация: читает raw всех кусков, на стенде
-- 10 млн строк — около 12 с на 8 ядрах; на 120 млн — порядка нескольких минут
-- CPU и ~800 МиБ на диске). Запускать в спокойное время:
--   ALTER TABLE argus.events MATERIALIZE INDEX idx_text;
--   ALTER TABLE argus.wazuh_alerts MATERIALIZE INDEX idx_text;
-- Ход мутации: SELECT * FROM system.mutations WHERE NOT is_done.
ALTER TABLE argus.events ADD INDEX IF NOT EXISTS idx_text lowerUTF8(concat(raw, actor_name, object, node, src_ip, dst_ip, action, toString(attrs))) TYPE ngrambf_v1(4, 65536, 3, 0) GRANULARITY 1;
ALTER TABLE argus.wazuh_alerts ADD INDEX IF NOT EXISTS idx_text lowerUTF8(raw) TYPE ngrambf_v1(4, 65536, 3, 0) GRANULARITY 1;
